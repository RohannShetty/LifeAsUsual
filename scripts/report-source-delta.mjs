#!/usr/bin/env node
/**
 * Report how far the pinned ./source submodule has fallen behind upstream.
 *
 * The inherited edition translates a pinned commit. Upstream keeps correcting
 * facts, links and numbers in that book, so the pinned edition can carry claims
 * the author already fixed. This lists the drift and the India chapter files a
 * reviewer must compare; it does not decide whether a correction changes the
 * advice and never marks a chapter re-verified.
 *
 * Usage: node scripts/report-source-delta.mjs [--out <path>]
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const BT = String.fromCharCode(96);
const repoRoot = path.resolve(".");
const submodule = path.join(repoRoot, "source");
const outArg = process.argv.indexOf("--out");
const outPath = outArg === -1
  ? path.join(repoRoot, "reports/india-first-inventory/source-submodule-delta.md")
  : path.resolve(process.argv[outArg + 1]);

function git(args, cwd = submodule) {
  return execFileSync("git", ["-c", "core.quotepath=false", ...args], { cwd, encoding: "utf8" }).trim();
}

if (!fs.existsSync(path.join(submodule, ".git"))) {
  console.error("No ./source submodule checkout; cannot compute the delta.");
  process.exit(1);
}

const pinned = git(["rev-parse", "HEAD"]);
const pinnedSubject = git(["log", "-1", "--pretty=%s|%cs|%h"]);
const upstreamRef = git(["rev-parse", "--abbrev-ref", "origin/HEAD"]);
const upstream = git(["rev-parse", upstreamRef]);
const count = Number(git(["rev-list", "--count", pinned + ".." + upstreamRef]));

const log = count === 0 ? "" : git([
  "log", "--reverse", "--date=short", "--pretty=format:%h%x09%ad%x09%s",
  pinned + ".." + upstreamRef, "--", "book", "README.md", "other-languages"
]);

const CHAPTER_FILE = /book\/(\d{2})-([^/]+)\.md$/;
function indiaChapterFile(changedPath) {
  const match = changedPath.match(CHAPTER_FILE);
  if (!match) return null;
  const dir = path.join(repoRoot, "data/en-in/chapters");
  const prefix = match[1] + "-";
  const file = fs.existsSync(dir)
    ? fs.readdirSync(dir).find((name) => name.startsWith(prefix) && name.endsWith(".json"))
    : null;
  return file ? "data/en-in/chapters/" + file : null;
}

const commits = [];
for (const line of log.split("\n").filter(Boolean)) {
  const parts = line.split("\t");
  const hash = parts[0];
  const date = parts[1];
  const subject = parts.slice(2).join("\t");
  const files = git(["show", "--name-only", "--pretty=format:", hash])
    .split("\n").map((file) => file.trim()).filter(Boolean);
  const chapters = [...new Set(files.map(indiaChapterFile).filter(Boolean))];
  commits.push({ hash, date, subject, files, chapters });
}

const byChapter = new Map();
for (const commit of commits) {
  for (const chapter of commit.chapters) {
    const entry = byChapter.get(chapter) ?? { commits: [], files: new Set() };
    entry.commits.push(commit.hash);
    for (const file of commit.files) if (indiaChapterFile(file) === chapter) entry.files.add(file);
    byChapter.set(chapter, entry);
  }
}

const codify = (value) => BT + value + BT;
const correctionLike = commits.filter((commit) => /^F\d+\b|修正|纠正|核实|替换|不再|区分|还原|删除/.test(commit.subject));
const lines = [];
lines.push("# Source submodule delta - inherited edition vs upstream");
lines.push("");
lines.push("Generated by " + codify("node scripts/report-source-delta.mjs") + ". This is a review queue, not a verification result.");
lines.push("");
lines.push("- Pinned commit: " + codify(pinned.slice(0, 12)) + " (" + pinnedSubject.replaceAll("|", " / ") + ")");
lines.push("- Upstream " + codify(upstreamRef) + ": " + codify(upstream.slice(0, 12)));
lines.push("- Commits touching the book, README or other-language notes: **" + commits.length + "**");
lines.push("- Commits whose message reads like a factual or source correction: **" + correctionLike.length + "**");
lines.push("");
lines.push("## Why this matters");
lines.push("");
lines.push("The approved India edition translates the pinned commit. Upstream has continued to correct facts, dead source links and numeric errors in the same book. An upstream correction inside a chapter this edition ships is a possible defect in the shipped India draft. Nothing here has been applied or re-verified: every affected chapter is **UNASSESSED** until a reviewer compares the correction against the India adaptation.");
lines.push("");
lines.push("## Chapters touched by upstream corrections");
lines.push("");
if (byChapter.size === 0) {
  lines.push("No chapter files changed upstream in this window.");
} else {
  lines.push("| India chapter file | Upstream commits | Upstream book files | Status |");
  lines.push("| --- | --- | --- | --- |");
  for (const [chapter, entry] of [...byChapter.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const shown = entry.commits.slice(0, 6).join(", ") + (entry.commits.length > 6 ? ", ..." : "");
    lines.push("| " + codify(chapter) + " | " + entry.commits.length + " (" + shown + ") | " + [...entry.files].map((file) => codify(file)).join("<br>") + " | UNASSESSED |");
  }
}
lines.push("");
lines.push("## Commit log");
lines.push("");
lines.push("| Commit | Date | Subject | India chapter files |");
lines.push("| --- | --- | --- | --- |");
for (const commit of commits) {
  lines.push("| " + codify(commit.hash) + " | " + commit.date + " | " + commit.subject.replaceAll("|", "\\|") + " | " + (commit.chapters.length ? commit.chapters.map((chapter) => codify(chapter)).join(", ") : "-") + " |");
}
lines.push("");
lines.push("## What a reviewer has to do");
lines.push("");
lines.push("1. For each chapter row above, read the upstream diff and the shipped India chapter JSON side by side.");
lines.push("2. Decide per affected tip: the correction does not change the advice (record why), the shipped tip needs the same fix (open a content change), or the India adaptation already handled it (cite the tip evidence).");
lines.push("3. Record the decision against the tip in the P1 disposition ledger rather than editing this report.");
lines.push("4. Re-pin the submodule only after the affected chapters are dispositioned, so the pin never moves ahead of the review.");
lines.push("");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log("Source delta: " + commits.length + " book commit(s) behind, " + byChapter.size + " chapter file(s) affected -> " + path.relative(repoRoot, outPath));
